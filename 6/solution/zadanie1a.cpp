// Задание 1, часть А. Динамическая память для одиночного объекта int.
#include <iostream>
using namespace std;

int main() {
    int *p = new int;          // Выделяем память для одного int

    cout << "Введите значение: ";
    cin >> *p;                 // Читаем значение прямо в выделенную ячейку

    cout << "Значение по указателю: " << *p << endl;

    delete p;                  // Освобождаем память
    p = nullptr;               // Хорошая практика: обнулить указатель после delete

    return 0;
}
